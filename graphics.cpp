/*
 * graphics.cpp
 *
 * Every sprite is 16-colour: width, height, then each frame as height rows
 * of (width + 1) / 2 bytes, two pixels a byte (left pixel in the low
 * nibble). Values are indices into PAL (screen.cpp); 0 is transparent.
 * Draw them with screen::draw(x, y, sprite, frame).
 *
 * The arrays marked "Placeholder" were made from the Arduboy's 1-bit art:
 * one random colour per sprite (per tile for the tile sets), outlines in 1.
 * To replace one, paint a PNG and paste the output of
 *     python tools/sprites.py convert art/<name>.png <name> --tile W H
 * over it; `python tools/sprites.py export art` gives a PNG of each sprite
 * as it is now to start from. Keep the frame order: the game picks frames
 * by number (e.g. MIRROR = 8 for Poulet's left-facing frames).
 */

